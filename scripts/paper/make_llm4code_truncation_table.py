"""Extract truncation-rate table for §4 of the LLM4Code paper.

For each APPS-252 config (config = one JSONL file), counts the fraction of
samples where the model never emitted ``</think>`` — the reasoning phase hit
the token cap before terminating. This is the "truncation rate" reported
in ``docs/decoder_comparison_cot_apps_{qwen3,deepseek}.md``.

Text-only check (does the string ``</think>`` appear in the sample text?),
mirroring :func:`bench.eval.cot_efficiency.extract_think_span`. No tokenizer
needed; the numbers reconcile with the docs.

Usage:
    uv run python scripts/paper/make_llm4code_truncation_table.py

Writes ``paper/llm4code/tables/table_4_truncation.{md,tex}``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
TABLES_DIR = REPO_ROOT / "paper" / "llm4code" / "tables"
# Sibling paper repo (Overleaf-linked); mirror .tex + .md there if it exists.
# Same pattern as make_llm4code_tables.py — prevents paper-repo drift from
# forgotten manual copies.
TABLES_DIR_PAPER = REPO_ROOT.parent / "pless-for-coding-paper" / "tables"


THINK_END = "</think>"


# Configs to include in the truncation table. One row per config; multiple
# configs per model. Baselines + p-less family so §4 shows the contrast.
CONFIGS: dict[str, list[tuple[str, str]]] = {
    "Qwen3-8B": [
        # (label, JSONL path relative to REPO_ROOT)
        ("top-p @0.95, T=1.0", "results/pless_cot_efficiency_vllm/Qwen--Qwen3-8B/ATCODER_interview_all_252/temp_p0.95_think_t1.0_t1.0.jsonl"),
        ("top-k @20, T=1.0", "results/pless_cot_efficiency_vllm/Qwen--Qwen3-8B/ATCODER_interview_all_252/temp_k20_think_t1.0_t1.0.jsonl"),
        ("top-p @0.95 + top-k @20, T=0.6", "results/pless_cot_efficiency_vllm/Qwen--Qwen3-8B/ATCODER_interview_all_252/temp_p0.95_k20_think_t0.6_t0.6.jsonl"),
        ("p-less, T=1.0", "results/pless_cot_efficiency_vllm/Qwen--Qwen3-8B/ATCODER_interview_all_252/pless_think_t1.0_t1.0.jsonl"),
        ("p-less-norm, T=1.0", "results/pless_cot_efficiency_vllm/Qwen--Qwen3-8B/ATCODER_interview_all_252/pless_norm_think_t1.0_t1.0.jsonl"),
    ],
    "DeepSeek-R1-Distill-Llama-8B": [
        ("top-p @0.95, T=0.6", "results/_deepseek_fixed_full252/deepseek-ai--DeepSeek-R1-Distill-Llama-8B/ATCODER_interview/temp_p0.95_think_t0.6_t0.6.jsonl"),
        ("top-k @20, T=1.0", "results/_deepseek_fixed_full252/deepseek-ai--DeepSeek-R1-Distill-Llama-8B/ATCODER_interview/temp_k20_think_t1.0_t1.0.jsonl"),
        ("top-p @0.95 + top-k @20, T=0.6", "results/_deepseek_fixed_full252/deepseek-ai--DeepSeek-R1-Distill-Llama-8B/ATCODER_interview/temp_p0.95_k20_think_t0.6_t0.6.jsonl"),
        ("p-less, T=1.0", "results/_deepseek_fixed_full252/deepseek-ai--DeepSeek-R1-Distill-Llama-8B/ATCODER_interview/pless_think_t1.0_t1.0.jsonl"),
        ("p-less-norm, T=1.0", "results/_deepseek_fixed_full252/deepseek-ai--DeepSeek-R1-Distill-Llama-8B/ATCODER_interview/pless_norm_think_t1.0_t1.0.jsonl"),
    ],
}


def _truncation_rate(jsonl_path: Path) -> tuple[int, int, int]:
    """Return (num_samples_truncated, num_samples_total, num_tasks).

    Reads ``samples_with_thinking`` (raw output including the reasoning phase);
    ``samples`` is the post-strip code and doesn't include ``</think>``.
    A sample is truncated iff ``</think>`` never appears in the raw output.
    """
    truncated = 0
    total = 0
    tasks = 0
    with jsonl_path.open() as f:
        for line in f:
            d = json.loads(line)
            tasks += 1
            swt = d.get("samples_with_thinking") or []
            for s in swt:
                text = s if isinstance(s, str) else (s.get("text") if isinstance(s, dict) else str(s))
                total += 1
                if text is None or THINK_END not in text:
                    truncated += 1
    return truncated, total, tasks


def _render_markdown() -> str:
    lines = [
        "# Table 4 — Truncation rates on APPS-252 (ATCODER-interview, thinking-ON)",
        "",
        "Fraction of samples where `</think>` was never emitted (reasoning phase hit token cap). Auto-generated by `scripts/paper/make_llm4code_truncation_table.py`.",
        "",
    ]
    for model, rows in CONFIGS.items():
        lines.append(f"## {model}\n")
        lines.append("| Decoder | truncation % | n_samples | n_tasks |")
        lines.append("|:---|---:|---:|---:|")
        for label, rel in rows:
            path = REPO_ROOT / rel
            if not path.exists():
                print(f"GAP: {model} | {label} | missing: {rel}", file=sys.stderr)
                lines.append(f"| {label} | — | — | — |")
                continue
            trunc, total, tasks = _truncation_rate(path)
            if tasks != 252:
                print(f"WRONG_NUM_TASKS: {model} | {label} | got {tasks} tasks, expected 252: {rel}", file=sys.stderr)
                continue
            rate = 100.0 * trunc / total if total else 0.0
            lines.append(f"| {label} | {rate:.1f}% | {total} | {tasks} |")
        lines.append("")
    return "\n".join(lines)


def _render_latex() -> str:
    lines = [
        "% Table 4 — Truncation rates on APPS-252",
        "% Auto-generated by scripts/paper/make_llm4code_truncation_table.py — do not hand-edit.",
        "",
    ]
    for model, rows in CONFIGS.items():
        safe_model = model.replace(".", "").replace("-", "_")
        body: list[str] = []
        for label, rel in rows:
            path = REPO_ROOT / rel
            if not path.exists():
                body.append(f"    {label.replace('%', r'\%')} & --- & --- & --- \\\\")
                continue
            trunc, total, tasks = _truncation_rate(path)
            if tasks != 252:
                continue
            rate = 100.0 * trunc / total if total else 0.0
            safe_label = label.replace("%", r"\%").replace("_", r"\_").replace("α", r"$\alpha$")
            body.append(f"    {safe_label} & {rate:.1f}\\% \\\\")
        if not body:
            continue
        lines.extend([
            r"\begin{table}[t]",
            r"\centering",
            rf"\caption{{Truncation rates on APPS-252 (252 tasks, $n{{=}}10$, thinking-ON) --- {model.replace('_', r'\_')}.}}",
            rf"\label{{tab:4_trunc_{safe_model}}}",
            r"\begin{tabular}{lr}",
            r"\toprule",
            r"Decoder & truncation \% \\",
            r"\midrule",
            *body,
            r"\bottomrule",
            r"\end{tabular}",
            r"\end{table}",
            "",
        ])
    return "\n".join(lines)


def main() -> None:
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    (TABLES_DIR / "table_4_truncation.md").write_text(_render_markdown())
    (TABLES_DIR / "table_4_truncation.tex").write_text(_render_latex())
    print(f"Wrote truncation table to {TABLES_DIR.relative_to(REPO_ROOT)}/table_4_truncation.{{md,tex}}", file=sys.stderr)
    if TABLES_DIR_PAPER.exists():
        for src in (TABLES_DIR / "table_4_truncation.tex", TABLES_DIR / "table_4_truncation.md"):
            (TABLES_DIR_PAPER / src.name).write_text(src.read_text())
        print(f"mirrored table_4_truncation.{{tex,md}} to {TABLES_DIR_PAPER}", file=sys.stderr)


if __name__ == "__main__":
    main()
